"""
Points Ledger Domain (G-1 foundation)
Owned by: Ankush (Gamification, Challenges & Competitions)

Pure, immutable models and validation for future points-ledger rows, matching the
proposed `points_ledger` contract in docs/GAMIFICATION_INTEGRATION_PLAN.md §2.
Nothing here touches a database, and nothing in the application calls it yet.

Concurrency: these functions only *prepare* rows. Duplicate protection and
atomicity must be enforced by the database (UNIQUE(event_key), single transaction,
INSERT ... ON CONFLICT DO NOTHING), never by these pure functions.

Decision status recorded for this module (2026-10-27):
- D-2 APPROVED by Ankush: 'py_master' is equivalent to 'assessment.subj_python.high_score'.
- D-6 APPROVED by Ankush: legacy badge equivalents live in gamification_service.py.
  Neither approval authorises database changes or router integration.
- D-1 (revocation model) NOT approved: no revocation support here.
- D-3 (ledger rows for zero-point rewards) NOT approved: callers must choose a
  ZeroPointPolicy explicitly; there is no default.
- D-5 (user deletion / retention) NOT resolved: no deletion or retention logic here.
"""

import re
from dataclasses import dataclass
from enum import StrEnum

# Same owner module. The private validators are reused on purpose so ledger rows follow
# exactly the same rules as the rest of the gamification service.
from .gamification_service import (
    ChallengeRewardDecision,
    InvalidTrustedInputError,
    RewardReason,
    _require_badge_key,
    _require_int,
    reward_event_key,
)

# Column widths from the proposed points_ledger table (GAMIFICATION_INTEGRATION_PLAN §2.1).
MAX_EVENT_ID_LENGTH = 64
MAX_EVENT_KEY_LENGTH = 255
MAX_USER_ID_LENGTH = 64
MAX_SOURCE_TYPE_LENGTH = 32
MAX_SOURCE_ID_LENGTH = 64

DAILY_CHALLENGE_SOURCE = "daily_challenge"
LIVE_EVENT_ID_PREFIX = "rwd_"
BACKFILL_V1_EVENT_ID_PREFIX = "rwd_v1_"

_EVENT_ID_RE = re.compile(r"rwd_[A-Za-z0-9_]+")
_SUBMISSION_ID_RE = re.compile(r"[A-Za-z0-9_]+")


class LedgerOrigin(StrEnum):
    LIVE = "live"
    BACKFILL_V1 = "backfill_v1"


class ZeroPointPolicy(StrEnum):
    """How to treat rewards worth 0 points until D-3 is decided."""
    RECORD = "record"
    SKIP = "skip"


class LedgerDecisionReason(StrEnum):
    RECORD = "record"
    NOT_A_REWARD = "not_a_reward"            # wrong answer or repeat submission
    ZERO_POINTS_SKIPPED = "zero_points_skipped"


@dataclass(frozen=True)
class LedgerEvent:
    """One proposed points_ledger row. created_at is left to the database default
    (live) or copied from the V1 submission (backfill); it is not part of the pure domain."""
    event_id: str
    event_key: str
    user_id: str
    source_type: str
    source_id: str
    points_delta: int
    reason: RewardReason
    origin: LedgerOrigin
    badge_key: str | None = None


@dataclass(frozen=True)
class LedgerAwardDecision:
    """Whether a reward should produce a ledger row, and the row if so."""
    reason: LedgerDecisionReason
    event: LedgerEvent | None = None

    @property
    def should_record(self) -> bool:
        return self.event is not None


def _require_max_length(value: str, field: str, limit: int) -> None:
    if len(value) > limit:
        raise InvalidTrustedInputError(f"{field} exceeds {limit} characters")


def _as_member(value: object, enum_type: type[StrEnum], field: str):
    try:
        return enum_type(value)
    except ValueError:
        raise InvalidTrustedInputError(
            f"{field} must be one of {', '.join(m.value for m in enum_type)}; got {value!r:.40}"
        ) from None


def backfill_event_id(submission_id: str) -> str:
    """Deterministic id for a V1 backfill row: 'rwd_v1_<submission id>'
    (same expression as the plan's backfill SQL: 'rwd_v1_' || s.id)."""
    if not isinstance(submission_id, str) or not _SUBMISSION_ID_RE.fullmatch(submission_id):
        raise InvalidTrustedInputError(f"submission_id must match [A-Za-z0-9_]+; got {submission_id!r:.40}")
    event_id = BACKFILL_V1_EVENT_ID_PREFIX + submission_id
    _require_max_length(event_id, "event_id", MAX_EVENT_ID_LENGTH)
    return event_id


def prepare_ledger_event(
    *,
    event_id: str,
    user_id: str,
    source_type: str,
    source_id: str,
    points: int,
    reason: RewardReason,
    origin: LedgerOrigin,
    badge_key: str | None = None,
) -> LedgerEvent:
    """Validate trusted server-side inputs and build one ledger row.

    - user_id must be the authenticated user; points must come from trusted config.
    - event_key is reward_event_key(user_id, source_type, source_id): the same key
      for a live award and its V1 backfill, so the database can never hold both.
    - event_id is generated by the caller (live: 'rwd_<hex>'; backfill: backfill_event_id()).
    Raises InvalidTrustedInputError for any malformed value.
    """
    event_key = reward_event_key(user_id, source_type, source_id)  # validates the three parts
    _require_max_length(user_id, "user_id", MAX_USER_ID_LENGTH)
    _require_max_length(source_type, "source_type", MAX_SOURCE_TYPE_LENGTH)
    _require_max_length(source_id, "source_id", MAX_SOURCE_ID_LENGTH)
    _require_max_length(event_key, "event_key", MAX_EVENT_KEY_LENGTH)
    _require_int(points, "points", minimum=0)
    reason = _as_member(reason, RewardReason, "reason")
    if reason is not RewardReason.CORRECT_ANSWER:
        raise InvalidTrustedInputError(f"reason {reason.value!r} is not a reward and must not reach the ledger")
    origin = _as_member(origin, LedgerOrigin, "origin")
    if badge_key is not None:
        _require_badge_key(badge_key, "badge_key")

    if not isinstance(event_id, str) or not _EVENT_ID_RE.fullmatch(event_id):
        raise InvalidTrustedInputError(f"event_id must match rwd_[A-Za-z0-9_]+; got {event_id!r:.40}")
    _require_max_length(event_id, "event_id", MAX_EVENT_ID_LENGTH)
    is_backfill_id = event_id.startswith(BACKFILL_V1_EVENT_ID_PREFIX)
    if is_backfill_id != (origin is LedgerOrigin.BACKFILL_V1):
        raise InvalidTrustedInputError(
            f"event_id prefix {BACKFILL_V1_EVENT_ID_PREFIX!r} is reserved for origin 'backfill_v1'"
        )

    return LedgerEvent(
        event_id=event_id,
        event_key=event_key,
        user_id=user_id,
        source_type=source_type,
        source_id=source_id,
        points_delta=points,
        reason=reason,
        origin=origin,
        badge_key=badge_key,
    )


def decide_challenge_ledger_award(
    user_id: str,
    decision: ChallengeRewardDecision,
    *,
    event_id: str,
    origin: LedgerOrigin,
    zero_point_policy: ZeroPointPolicy,
) -> LedgerAwardDecision:
    """Map a daily-challenge reward decision to a ledger decision.

    Wrong answers and repeat submissions are not rewards and never produce a row.
    A correct answer worth 0 points follows zero_point_policy (no default until D-3).
    Badges are still awarded through user_badges regardless; badge_key here is only
    the informational link stored on the ledger row.
    """
    if not isinstance(decision, ChallengeRewardDecision):
        raise InvalidTrustedInputError("decision must be a ChallengeRewardDecision")
    policy = _as_member(zero_point_policy, ZeroPointPolicy, "zero_point_policy")
    if len(decision.achievements) > 1:
        raise InvalidTrustedInputError("a ledger row can reference at most one badge")

    if decision.reason is not RewardReason.CORRECT_ANSWER:
        return LedgerAwardDecision(LedgerDecisionReason.NOT_A_REWARD)
    if decision.points_awarded == 0 and policy is ZeroPointPolicy.SKIP:
        return LedgerAwardDecision(LedgerDecisionReason.ZERO_POINTS_SKIPPED)

    event = prepare_ledger_event(
        event_id=event_id,
        user_id=user_id,
        source_type=DAILY_CHALLENGE_SOURCE,
        source_id=decision.challenge_id,
        points=decision.points_awarded,
        reason=decision.reason,
        origin=origin,
        badge_key=decision.achievements[0].badge_key if decision.achievements else None,
    )
    return LedgerAwardDecision(LedgerDecisionReason.RECORD, event)
